"""Parcel C's acceptance criterion: the Postgres connector and the model-free seed.

**Rewritten 2026-08-03 against Postgres.** The previous version of this file was written
against `SqliteConnector`, it passed cleanly, and it was measuring a connector the project
no longer supports (decision #40). That is a **design-holder** error, not an
implementer's, and it is a different failure from the one the contract-first rule exists to
prevent: authoring a contract before the implementation stops an implementer grading
themselves, and does nothing about the design holder scoping it wrong. A contract can be
honest, thorough, passed, and about the wrong subject.

**Do not edit this file to make it pass.** If a test looks wrong, stop and say so.

Three things carry this parcel, and the first two are new here.

**The error taxonomy is keyed on SQLSTATE, never on message text.** The predecessor's
classifier was a four-marker regex over exception prose, defaulting to `ConnectionError`,
and an adversarial review found it wrong in *both* directions — `no such function` and a
bad arity landed in the crash stratum, a corrupt database file landed in the wrong-answer
stratum. That was not sloppiness; SQLite reports faults as prose and there was nothing
else to match on. Postgres gives structured codes, so the distinction that decides whether
a turn is a crash or a wrong answer — the distinction whose miscoding retired the
pre-2026-07-25 numbers — becomes a lookup:

* class ``42`` — syntax error or access-rule violation. **A query fault.** The statement
  reached the engine and the engine rejected it.
* class ``08`` — connection exception. **Infrastructure.**
* classes ``53`` / ``57`` — insufficient resources, operator intervention.
  **Infrastructure.**

A regex over English can be wrong in both directions. A SQLSTATE class cannot.

**A query `govern` permits must be one the connector executes.** This is the cross-parcel
property that nobody owned, and its absence meant the intersection of "govern permits" and
"the connector executes" was **empty** for the whole of 2026-08-03 — `govern` licenses
`{schema}.{physical_name}`, SQLite rejected the qualified form, and nothing tested the
pair. It did not surface because the grader re-executed outside governance. Postgres-only
makes it native; this test is what keeps it that way.

**The seed is what makes retrieval measurable before a curator exists.** ADR 0005's claim
that "steps 6-9 are measurable with no model at all" rests entirely on it, so it is
asserted at the socket rather than trusted.

**When no server is reachable these tests skip with a printed reason**, never silently:
the reason is the whole point, and a silent skip and a pass produce the same green tick.
"""

