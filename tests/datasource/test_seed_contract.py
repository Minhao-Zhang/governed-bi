#: SQLSTATEs that must classify as a **query fault**, with the statement that produces
#: each. Every one of these was misclassified as infrastructure by the predecessor.
QUERY_FAULTS: tuple[tuple[str, str, str], ...] = (
    ("42P01", "undefined_table", "SELECT 1 FROM no_such_table_xyz"),
    ("42703", "undefined_column", "SELECT no_such_column_xyz FROM {t}"),
    ("42601", "syntax_error", "SELEKT 1"),
    ("42883", "undefined_function", "SELECT no_such_fn_xyz(1)"),
    ("42883", "wrong_arity", "SELECT abs(1, 2)"),
)


def _dsn() -> str:
    """The DSN, from the environment or `.env`. Never logged — it carries credentials."""
    dsn = os.environ.get("GOVERNED_BI_PG_DSN") or os.environ.get("PG_RENAME_DECOY_DSN")
    if dsn:
        return dsn
    env = pathlib.Path(__file__).resolve().parent.parent.parent / ".env"
    if env.exists():
        for line in env.read_text(encoding="utf-8").splitlines():
            if line.strip().startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            if key.strip() in ("GOVERNED_BI_PG_DSN", "PG_RENAME_DECOY_DSN"):
                return value.strip().strip("\"'")
    return ""


@pytest.fixture(scope="module")
def dsn() -> str:
    """Skip loudly when there is no server. The reason must reach the reader."""
    value = _dsn()
    if not value:
        pytest.skip(
            "no Postgres DSN: set GOVERNED_BI_PG_DSN or PG_RENAME_DECOY_DSN. "
            "Parcel C is Postgres-only (decision #40) and a connector cannot be "
            "tested without a server; these tests are not optional, they are pending."
        )
    import psycopg

    try:
        with psycopg.connect(value, connect_timeout=5):
            pass
    except Exception as err:  # pragma: no cover - environment dependent
        pytest.skip(f"Postgres unreachable ({type(err).__name__}); see the DSN's host")
    return value


